#!/usr/bin/env python3
"""pack-sh.py -- shrink sh.tcl so the CURRENT bridge build can boot it.

WHY THIS EXISTS
  The adapter boots the shell with  ip.Eval(window.__shTcl).  wacl copies that
  whole string onto the WebAssembly stack, which holds about 64 KB.  A longer
  string does not raise an error: it overruns the stack ("memory access out of
  bounds") and can take the shared interpreter down for every window.
  The readable sh.tcl is well past 64 KB, so it must not be embedded as is
  until the adapter is changed to load it from the file system (see
  bridge-notes: "the 64 KB boot limit").

WHAT IT DOES
  Reads sh.tcl, compresses it (raw deflate), writes it as base64 into a small
  Tcl stub that inflates and evaluates it.  The stub is plain Tcl 9 and needs
  no runtime change.  Embed the OUTPUT (sh-boot.tcl) where the build embeds
  sh.tcl today.  Edit sh.tcl, never the output.

USAGE
  python3 pack-sh.py [sh.tcl [sh-boot.tcl]]
"""
import base64, sys, zlib

LIMIT = 62000   # bytes of stub; the hard limit is ~64000 (65536 minus the adapter's wrapper)

src = sys.argv[1] if len(sys.argv) > 1 else 'sh.tcl'
dst = sys.argv[2] if len(sys.argv) > 2 else 'sh-boot.tcl'

data = open(src, 'rb').read()
c = zlib.compressobj(9, zlib.DEFLATED, -15)
raw = c.compress(data) + c.flush()
b64 = base64.b64encode(raw).decode()
lines = [b64[i:i + 76] for i in range(0, len(b64), 76)]

stub = (
    '# sh-boot.tcl -- GENERATED by pack-sh.py from sh.tcl.  Do not edit; edit sh.tcl.\n'
    '# The payload is sh.tcl, deflated and base64-encoded, to fit the 64 KB boot limit.\n'
    'eval [encoding convertfrom utf-8 [zlib inflate [binary decode base64 {\n'
    + '\n'.join(lines) + '\n}]]]\n'
)
open(dst, 'w').write(stub)
print('%s: %d bytes -> %s: %d bytes (limit %d)' % (src, len(data), dst, len(stub), LIMIT))
if len(stub) > LIMIT:
    sys.exit('too big for the boot limit: trim sh.tcl (mostly help text)')
